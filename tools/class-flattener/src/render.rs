//! Text output: one Java-like listing of everything the flattened class runs.

use std::collections::{BTreeMap, BTreeSet};

use rustc_hash::{FxHashMap, FxHashSet};
use std::fmt::Write as _;
use std::ptr;

use tree_sitter::Node;

use crate::calls::{self, CallKind, CallOutcome, CallSite, CtorCall, CtorOutcome, Resolver};
use crate::hierarchy::{Hierarchy, Implementation, Slot};
use crate::model::{JavaFile, MethodDecl, TypeDecl};
use crate::source::SourceTree;

pub struct Options {
    /// Only these method names; `<init>` selects constructors. Empty = all.
    pub methods: Vec<String>,
    pub inline: bool,
    pub summary: bool,
    pub source_label: String,
}

impl Options {
    const fn wants_all(&self) -> bool {
        self.methods.is_empty()
    }

    fn wants_method(&self, name: &str) -> bool {
        self.wants_all() || self.methods.iter().any(|m| m == name)
    }

    fn wants_constructors(&self) -> bool {
        self.wants_method("<init>")
    }
}

/// Upper bound on nested inlining; real chains are far shorter.
const MAX_INLINE_DEPTH: usize = 32;

type DeclKey = *const MethodDecl;

pub struct Renderer<'a> {
    hierarchy: &'a Hierarchy,
    resolver: Resolver<'a>,
    options: &'a Options,
    calls: FxHashMap<DeclKey, Vec<(CallSite, CallOutcome)>>,
    reached: FxHashSet<DeclKey>,
}

impl<'a> Renderer<'a> {
    pub fn new(source: &'a SourceTree, hierarchy: &'a Hierarchy, options: &'a Options) -> Self {
        let resolver = Resolver { source, hierarchy };
        let mut renderer = Self {
            hierarchy,
            resolver,
            options,
            calls: FxHashMap::default(),
            reached: FxHashSet::default(),
        };
        let decls: Vec<&'static MethodDecl> = hierarchy
            .slots
            .iter()
            .flat_map(|slot| slot.decls.iter().copied())
            .chain(hierarchy.classes.iter().flat_map(|c| c.constructors.iter()))
            .collect();
        for decl in decls {
            let Some(body) = decl.body else { continue };
            let analyzed = calls::collect_calls(decl.file, body)
                .into_iter()
                .map(|call| {
                    let outcome = renderer.resolver.resolve_call(decl, &call);
                    (call, outcome)
                })
                .collect();
            renderer.calls.insert(decl, analyzed);
        }
        renderer.compute_reached();
        renderer
    }

    /// Effective implementations plus everything reachable from them via
    /// super calls.
    fn compute_reached(&mut self) {
        let mut pending: Vec<&'static MethodDecl> = self
            .hierarchy
            .slots
            .iter()
            .filter_map(|slot| self.hierarchy.effective(slot).concrete())
            .collect();
        while let Some(decl) = pending.pop() {
            if !self.reached.insert(decl) {
                continue;
            }
            for (_, outcome) in self.calls.get(&(decl as DeclKey)).into_iter().flatten() {
                if let CallOutcome::Super(implementation) = outcome
                    && let Some(target) = implementation.concrete()
                {
                    pending.push(target);
                }
            }
        }
    }

    pub fn render(&self) -> String {
        let mut out = String::new();
        self.header(&mut out);
        let _ = writeln!(
            out,
            "class {} /* flattened */ {{",
            self.hierarchy.target.name
        );
        if self.options.wants_all() {
            self.fields(&mut out);
        }
        if self.options.wants_constructors() {
            self.constructors(&mut out);
        }
        self.methods(&mut out);
        out.push_str("}\n");
        out
    }

    fn header(&self, out: &mut String) {
        let h = self.hierarchy;
        let _ = writeln!(out, "// Flattened view of {}", h.target.fqn);
        let _ = writeln!(
            out,
            "// Source: {}. Generated by tools/class-flattener; not compilable Java.",
            self.options.source_label
        );
        out.push_str("//\n// Class chain (most derived first):\n");
        let width = h
            .classes
            .iter()
            .chain(&h.interfaces)
            .map(|t| t.display_name().len())
            .max()
            .unwrap_or(0);
        for class in &h.classes {
            let _ = writeln!(
                out,
                "//   {:width$}  {}",
                class.display_name(),
                class.file.rel_path
            );
        }
        if !h.interfaces.is_empty() {
            out.push_str("// Interfaces:\n");
            for interface in &h.interfaces {
                let via = h
                    .introduced_by(interface)
                    .map_or_default(|c| format!("  (via {})", c.display_name()));
                let _ = writeln!(
                    out,
                    "//   {:width$}  {}{via}",
                    interface.display_name(),
                    interface.file.rel_path
                );
            }
        }
        if !h.external.is_empty() {
            out.push_str("// Not in minecraft-src (members not flattened):\n");
            for external in &h.external {
                let _ = writeln!(
                    out,
                    "//   {} (from {})",
                    external.name,
                    external.from.display_name()
                );
            }
        }
        let parse_errors: Vec<String> = h
            .classes
            .iter()
            .chain(&h.interfaces)
            .filter(|t| !t.file.parse_error_lines.is_empty())
            .map(|t| {
                let lines: Vec<String> = t
                    .file
                    .parse_error_lines
                    .iter()
                    .map(ToString::to_string)
                    .collect();
                format!("{} lines {}", t.file.rel_path, lines.join(", "))
            })
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect();
        if !parse_errors.is_empty() {
            out.push_str("// WARNING: tree-sitter could not parse parts of these files; nearby results may be incomplete:\n");
            for error in parse_errors {
                let _ = writeln!(out, "//   {error}");
            }
        }
        out.push_str(
            "//\n\
             // Legend: ▶ runs for this class   ↳ reached through super   ✗ overridden, never reached\n\
             //         ○ abstract   · hidden static\n\
             //   `super →`         target of a super call\n\
             //   `dispatches to`   inherited code calling a method this class overrides\n\n",
        );
    }

    fn fields(&self, out: &mut String) {
        let mut seen: FxHashMap<&str, &str> = FxHashMap::default();
        for class in self.hierarchy.classes.iter().rev() {
            for field in &class.fields {
                for name in &field.names {
                    seen.entry(name).or_insert(class.display_name());
                }
            }
        }
        for ty in self
            .hierarchy
            .classes
            .iter()
            .chain(&self.hierarchy.interfaces)
        {
            if ty.fields.is_empty() {
                continue;
            }
            let _ = writeln!(out, "\t// ══════ fields: {} ══════", ty.display_name());
            for field in &ty.fields {
                let shadowed: Vec<&str> = field
                    .names
                    .iter()
                    .filter_map(|n| seen.get(n.as_str()).copied())
                    .filter(|owner| *owner != ty.display_name())
                    .collect();
                let note = if shadowed.is_empty() {
                    String::new()
                } else {
                    format!("  // shadows {}", shadowed.join(", "))
                };
                if self.options.summary {
                    let statik = if field.is_static { "static " } else { "" };
                    let _ = writeln!(
                        out,
                        "\t{statik}{} {};{note}",
                        field.ty,
                        field.names.join(", ")
                    );
                } else {
                    let text = reindent(ty.file, field.node, "\t");
                    let _ = writeln!(out, "{}{note}", text.trim_end());
                }
            }
            out.push('\n');
        }
    }

    fn constructors(&self, out: &mut String) {
        let target = self.hierarchy.target;
        if target.constructors.is_empty() {
            return;
        }
        let _ = writeln!(out, "\t// ══════ constructors ══════");
        let mut ancestors: Vec<&'static MethodDecl> = Vec::new();
        for ctor in &target.constructors {
            let mut chain = vec![ctor.qualified_signature()];
            let mut current = ctor;
            for _ in 0..MAX_INLINE_DEPTH {
                let Some(call) = self.resolver.resolve_constructor_call(current) else {
                    break;
                };
                match call.outcome {
                    CtorOutcome::Resolved(next) => {
                        chain.push(next.qualified_signature());
                        if !ancestors.iter().any(|a| ptr::eq(*a, next)) && next.owner != target.fqn
                        {
                            ancestors.push(next);
                        }
                        current = next;
                    }
                    CtorOutcome::ImplicitDefault(ty) => {
                        chain.push(format!("{}() (implicit default)", ty.display_name()));
                        break;
                    }
                    CtorOutcome::ImplicitCanonical(ty) => {
                        chain.push(format!(
                            "{}(…) (implicit canonical record constructor)",
                            ty.display_name()
                        ));
                        break;
                    }
                    CtorOutcome::NotFound => {
                        chain.push("NOT FOUND".to_owned());
                        break;
                    }
                    CtorOutcome::Ambiguous(options) => {
                        let options: Vec<String> = options.iter().map(|o| o.signature()).collect();
                        chain.push(format!("AMBIGUOUS: {}", options.join(" | ")));
                        break;
                    }
                    CtorOutcome::External => {
                        chain.push("(outside minecraft-src)".to_owned());
                        break;
                    }
                }
            }
            let _ = writeln!(out, "\t// {}", chain.join("\n\t//   → "));
        }
        out.push('\n');
        if self.options.summary {
            return;
        }
        for ctor in &target.constructors {
            self.decl(ctor, "\t", 0, out);
            out.push('\n');
        }
        if !self.options.inline {
            for ctor in ancestors {
                let _ = writeln!(
                    out,
                    "\t// ↳ {}  {}",
                    ctor.qualified_signature(),
                    ctor.location()
                );
                self.decl(ctor, "\t", 0, out);
                out.push('\n');
            }
        }
    }

    fn methods(&self, out: &mut String) {
        let h = self.hierarchy;
        let types: Vec<&'static TypeDecl> =
            h.classes.iter().chain(&h.interfaces).copied().collect();
        let mut groups: BTreeMap<usize, Vec<(&Slot, &'static MethodDecl)>> = BTreeMap::new();
        let mut unimplemented: Vec<(&Slot, Implementation)> = Vec::new();
        for slot in &h.slots {
            if !self.options.wants_method(&slot.name) {
                continue;
            }
            match h.effective(slot) {
                Implementation::Concrete(decl) => {
                    let rank = types
                        .iter()
                        .position(|t| t.fqn == decl.owner)
                        .unwrap_or(usize::MAX);
                    groups.entry(rank).or_default().push((slot, decl));
                }
                other => unimplemented.push((slot, other)),
            }
        }

        for (rank, mut slots) in groups {
            slots.sort_by_key(|(_, decl)| decl.line);
            let owner = types.get(rank).map_or("?", |t| t.display_name());
            let _ = writeln!(
                out,
                "\t// ══════ methods running {owner}'s implementation ══════\n"
            );
            for (slot, effective) in slots {
                self.slot_header(slot, out);
                if self.options.summary {
                    continue;
                }
                self.decl(effective, "\t", 0, out);
                if !self.options.inline {
                    for decl in &slot.decls {
                        if ptr::eq(*decl, effective) || !self.reached.contains(&(*decl as DeclKey))
                        {
                            continue;
                        }
                        let _ = writeln!(
                            out,
                            "\t// ↳ reached through super: {}  {}",
                            decl.qualified_signature(),
                            decl.location()
                        );
                        self.decl(decl, "\t", 0, out);
                    }
                }
                out.push('\n');
            }
            out.push('\n');
        }

        if !unimplemented.is_empty() {
            let _ = writeln!(out, "\t// ══════ abstract or unresolved ══════\n");
            for (slot, implementation) in unimplemented {
                if let Implementation::Conflict(decls) = &implementation {
                    let names: Vec<String> =
                        decls.iter().map(|d| d.qualified_signature()).collect();
                    let _ = writeln!(
                        out,
                        "\t// WARNING: conflicting interface defaults: {}",
                        names.join(", ")
                    );
                }
                self.slot_header(slot, out);
                out.push('\n');
            }
        }
    }

    fn slot_header(&self, slot: &Slot, out: &mut String) {
        let first = slot.decls[0];
        let kind = if slot.is_static { "static " } else { "" };
        if slot.decls.len() == 1 {
            let marker = if first.is_concrete() { "▶" } else { "○" };
            let _ = writeln!(
                out,
                "\t// ── {marker} {kind}{}  {}  {}",
                first.signature(),
                first.owner_display,
                first.location()
            );
            return;
        }
        let _ = writeln!(out, "\t// ── {kind}{} ──", first.signature());
        let effective = self.hierarchy.effective(slot).concrete();
        let width = slot
            .decls
            .iter()
            .map(|d| d.owner_display.len())
            .max()
            .unwrap_or(0);
        let loc_width = slot
            .decls
            .iter()
            .map(|d| d.location().len())
            .max()
            .unwrap_or(0);
        for decl in &slot.decls {
            let line = format!(
                "\t//   {} {:width$}  {:loc_width$}  {}",
                self.mark(slot, decl, effective).symbol(),
                decl.owner_display,
                decl.location(),
                self.super_summary(slot, decl)
            );
            let _ = writeln!(out, "{}", line.trim_end());
        }
    }

    fn mark(
        &self,
        slot: &Slot,
        decl: &'static MethodDecl,
        effective: Option<&'static MethodDecl>,
    ) -> Mark {
        if effective.is_some_and(|e| ptr::eq(e, decl)) {
            Mark::Effective
        } else if !decl.is_concrete() {
            Mark::Abstract
        } else if slot.is_static {
            Mark::HiddenStatic
        } else if self.reached.contains(&(decl as DeclKey)) {
            Mark::Reached
        } else {
            Mark::NeverReached
        }
    }

    /// Tab-separated rows for aggregating over many classes:
    /// `decl  target  signature  owner  class|interface  mark  super-shapes` for every
    /// declaration, and `dispatch  target  caller  callee  runs` for inherited
    /// `this` calls that land in an override.
    pub fn records(&self) -> String {
        let h = self.hierarchy;
        let target = h.target.display_name();
        let mut out = String::new();
        for slot in &h.slots {
            let effective = h.effective(slot).concrete();
            for decl in &slot.decls {
                let kind = if h.class_index(&decl.owner).is_some() {
                    "class"
                } else {
                    "interface"
                };
                let _ = writeln!(
                    out,
                    "decl\t{target}\t{}\t{}\t{kind}\t{}\t{}",
                    decl.signature(),
                    decl.owner_display,
                    self.mark(slot, decl, effective).name(),
                    self.super_shapes(slot, decl),
                );
            }
        }
        for slot in &h.slots {
            for decl in &slot.decls {
                if !self.reached.contains(&(*decl as DeclKey)) {
                    continue;
                }
                for (call, outcome) in self.calls.get(&(*decl as DeclKey)).into_iter().flatten() {
                    let CallOutcome::Dispatch(implementation) = outcome else {
                        continue;
                    };
                    let _ = writeln!(
                        out,
                        "dispatch\t{target}\t{}\t{}\t{}",
                        decl.qualified_signature(),
                        call.name,
                        impl_owner(implementation),
                    );
                }
            }
        }
        out
    }

    /// Shapes of `decl`'s super calls into its own slot, `;`-separated:
    /// `empty`, `none` (stops the chain), or e.g. `first,conditional`.
    fn super_shapes(&self, slot: &Slot, decl: &'static MethodDecl) -> String {
        let Some(body) = decl.body.filter(|_| decl.is_concrete()) else {
            return String::new();
        };
        if decl.is_empty() {
            return "empty".to_owned();
        }
        let shapes: Vec<String> = self
            .calls
            .get(&(decl as DeclKey))
            .into_iter()
            .flatten()
            .filter(|(call, outcome)| {
                call.name == slot.name && matches!(outcome, CallOutcome::Super(_))
            })
            .map(|(call, _)| {
                calls::call_shape(call.node, body)
                    .describe()
                    .replace(", ", ",")
            })
            .collect();
        if shapes.is_empty() {
            "none".to_owned()
        } else {
            shapes.join(";")
        }
    }

    /// How `decl` continues the chain: its super calls into the same slot.
    fn super_summary(&self, slot: &Slot, decl: &'static MethodDecl) -> String {
        if !decl.is_concrete() {
            return String::new();
        }
        if decl.is_empty() {
            return "empty".to_owned();
        }
        let Some(body) = decl.body else {
            return String::new();
        };
        let mut parts = Vec::new();
        for (call, outcome) in self.calls.get(&(decl as DeclKey)).into_iter().flatten() {
            let CallOutcome::Super(implementation) = outcome else {
                continue;
            };
            if call.name != slot.name {
                continue;
            }
            let shape = calls::call_shape(call.node, body);
            parts.push(format!(
                "super → {} [{}]",
                impl_owner(implementation),
                shape.describe()
            ));
        }
        if parts.is_empty() {
            let has_lower = slot
                .decls
                .iter()
                .skip_while(|d| !ptr::eq(**d, decl))
                .skip(1)
                .any(|d| d.is_concrete());
            return if has_lower && !slot.is_static {
                "no super call (chain stops here)".to_owned()
            } else {
                String::new()
            };
        }
        parts.join("; ")
    }

    /// Writes a declaration with call annotations, inlining super targets
    /// when requested.
    fn decl(&self, decl: &'static MethodDecl, indent: &str, depth: usize, out: &mut String) {
        let file = decl.file;
        let mut notes: BTreeMap<usize, Vec<String>> = BTreeMap::new();
        let mut inlines: BTreeMap<usize, Vec<(String, &'static MethodDecl)>> = BTreeMap::new();
        let inline = self.options.inline && depth < MAX_INLINE_DEPTH;

        for (call, outcome) in self.calls.get(&(decl as DeclKey)).into_iter().flatten() {
            let row = call.node.end_position().row;
            match outcome {
                CallOutcome::Super(implementation) => {
                    notes
                        .entry(row)
                        .or_default()
                        .push(format!("super → {}", describe(implementation)));
                    if inline && let Some(target) = implementation.concrete() {
                        inlines
                            .entry(insertion_row(call.node))
                            .or_default()
                            .push((format!("super.{}(…)", call.name), target));
                    }
                }
                CallOutcome::Dispatch(actual) => {
                    notes
                        .entry(row)
                        .or_default()
                        .push(format!("dispatches to {}", describe(actual)));
                }
                CallOutcome::Ambiguous(slots) => {
                    let options: Vec<String> = slots
                        .iter()
                        .map(|s| self.hierarchy.slots[*s].decls[0].signature())
                        .collect();
                    notes
                        .entry(row)
                        .or_default()
                        .push(format!("AMBIGUOUS overload: {}", options.join(" | ")));
                }
                CallOutcome::Unresolved if !matches!(call.kind, CallKind::This) => {
                    notes
                        .entry(row)
                        .or_default()
                        .push("super target not in minecraft-src".to_owned());
                }
                CallOutcome::Unresolved | CallOutcome::Direct => {}
            }
        }

        if decl.is_constructor()
            && let Some(call) = self.resolver.resolve_constructor_call(decl)
        {
            Self::constructor_note(&call, decl, inline, &mut notes, &mut inlines);
        }

        let start_row = decl.node.start_position().row;
        let end_row = decl.node.end_position().row;
        let lines: Vec<&str> = file.src.lines().collect();
        let base = leading_whitespace(lines.get(start_row).copied().unwrap_or(""));
        for row in start_row..=end_row {
            let line = lines.get(row).copied().unwrap_or("");
            let stripped = line.strip_prefix(base).unwrap_or_else(|| line.trim_start());
            if !stripped.is_empty() {
                out.push_str(indent);
                out.push_str(stripped);
            }
            if let Some(row_notes) = notes.get(&row) {
                let _ = write!(out, "  // {}", row_notes.join(" | "));
            }
            out.push('\n');
            for (label, target) in inlines.get(&row).into_iter().flatten() {
                let inner_indent = format!("{indent}{}", leading_whitespace(stripped));
                let _ = writeln!(
                    out,
                    "{inner_indent}// ▼ {label} = {}  {}",
                    target.qualified_signature(),
                    target.location()
                );
                self.decl(target, &inner_indent, depth + 1, out);
                let _ = writeln!(
                    out,
                    "{inner_indent}// ▲ end {}",
                    target.qualified_signature()
                );
            }
        }
    }

    fn constructor_note(
        call: &CtorCall,
        decl: &MethodDecl,
        inline: bool,
        notes: &mut BTreeMap<usize, Vec<String>>,
        inlines: &mut BTreeMap<usize, Vec<(String, &'static MethodDecl)>>,
    ) {
        let keyword = if call.is_super { "super" } else { "this" };
        let (row, prefix) = match call.node {
            Some(node) => (node.end_position().row, format!("{keyword}(…) →")),
            // The opening brace line of the body.
            None => (
                decl.body.map_or(decl.line - 1, |b| b.start_position().row),
                "implicit super() →".to_owned(),
            ),
        };
        let note = match &call.outcome {
            CtorOutcome::Resolved(target) => {
                if inline {
                    inlines
                        .entry(row)
                        .or_default()
                        .push((format!("{keyword}(…)"), target));
                }
                format!(
                    "{prefix} {}  {}",
                    target.qualified_signature(),
                    target.location()
                )
            }
            CtorOutcome::ImplicitDefault(ty) => {
                format!(
                    "{prefix} {}() (implicit default constructor)",
                    ty.display_name()
                )
            }
            CtorOutcome::ImplicitCanonical(ty) => {
                format!(
                    "{prefix} {}(…) (implicit canonical record constructor)",
                    ty.display_name()
                )
            }
            CtorOutcome::NotFound => format!("{prefix} NOT FOUND"),
            CtorOutcome::Ambiguous(options) => {
                let options: Vec<String> = options.iter().map(|o| o.signature()).collect();
                format!("{prefix} AMBIGUOUS: {}", options.join(" | "))
            }
            CtorOutcome::External => format!("{prefix} superclass not in minecraft-src"),
        };
        notes.entry(row).or_default().push(note);
    }
}

#[derive(Clone, Copy)]
enum Mark {
    Effective,
    Reached,
    NeverReached,
    Abstract,
    HiddenStatic,
}

impl Mark {
    const fn symbol(self) -> &'static str {
        match self {
            Self::Effective => "▶",
            Self::Reached => "↳",
            Self::NeverReached => "✗",
            Self::Abstract => "○",
            Self::HiddenStatic => "·",
        }
    }

    const fn name(self) -> &'static str {
        match self {
            Self::Effective => "effective",
            Self::Reached => "reached",
            Self::NeverReached => "never-reached",
            Self::Abstract => "abstract",
            Self::HiddenStatic => "hidden-static",
        }
    }
}

fn impl_owner(implementation: &Implementation) -> String {
    match implementation {
        Implementation::Concrete(decl) => decl.owner_display.clone(),
        Implementation::Abstract(decl) => format!("{} (abstract)", decl.owner_display),
        Implementation::Conflict(_) => "CONFLICT".to_owned(),
        Implementation::Missing => "?".to_owned(),
    }
}

fn describe(implementation: &Implementation) -> String {
    match implementation {
        Implementation::Concrete(decl) => {
            format!("{}  {}", decl.qualified_signature(), decl.location())
        }
        Implementation::Abstract(decl) => format!("{} (abstract)", decl.qualified_signature()),
        Implementation::Conflict(decls) => {
            let names: Vec<String> = decls.iter().map(|d| d.qualified_signature()).collect();
            format!("CONFLICT: {}", names.join(" | "))
        }
        Implementation::Missing => "?".to_owned(),
    }
}

/// Row after which an inlined body goes: the end of a simple enclosing
/// statement, or the call itself inside conditions and loop headers.
fn insertion_row(call: Node) -> usize {
    let mut node = call;
    while let Some(parent) = node.parent() {
        match parent.kind() {
            "expression_statement"
            | "return_statement"
            | "local_variable_declaration"
            | "throw_statement"
            | "yield_statement" => return parent.end_position().row,
            kind if kind.ends_with("_statement")
                || kind == "block"
                || kind == "lambda_expression" =>
            {
                break;
            }
            _ => node = parent,
        }
    }
    call.end_position().row
}

fn leading_whitespace(line: &str) -> &str {
    &line[..line.len() - line.trim_start().len()]
}

fn reindent(file: &JavaFile, node: Node, indent: &str) -> String {
    let lines: Vec<&str> = file.src.lines().collect();
    let start = node.start_position().row;
    let end = node.end_position().row;
    let base = leading_whitespace(lines.get(start).copied().unwrap_or(""));
    let mut out = String::new();
    for row in start..=end {
        let line = lines.get(row).copied().unwrap_or("");
        let stripped = line.strip_prefix(base).unwrap_or_else(|| line.trim_start());
        if !stripped.is_empty() {
            out.push_str(indent);
            out.push_str(stripped);
        }
        out.push('\n');
    }
    out
}
